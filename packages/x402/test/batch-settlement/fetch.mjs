// Copies the runtime code of x402's batch-settlement contracts and of Multicall3 from Base Sepolia into contracts.ts,
// which the batch-settlement test installs on Anvil at the same addresses. Tests never run it and never leave
// localhost; run it by hand to refresh the copies: `node packages/x402/test/batch-settlement/fetch.mjs && pnpm format`.
// x402BatchSettlement and ERC3009DepositCollector (https://github.com/x402-foundation/x402, contracts/evm/src) and
// Multicall3 (https://github.com/mds1/multicall3) are MIT-licensed; their notices are in LICENSE-x402 and
// LICENSE-multicall3 next to this file.
import { writeFileSync } from 'node:fs';
import { createPublicClient, http } from 'viem';
import { baseSepolia } from 'viem/chains';

const RPC_URL = 'https://sepolia.base.org';
// The addresses @x402/evm's batch-settlement scheme uses on every chain, and the facilitator's Multicall3.
const CONTRACTS = {
  BATCH_SETTLEMENT: '0x4020074e9dF2ce1deE5A9C1b5c3f541D02a10003',
  ERC3009_DEPOSIT_COLLECTOR: '0x4020806089470a89826cB9fB1f4059150b550004',
  MULTICALL3: '0xcA11bde05977b3631167028862bE2a173976CA11',
};

const client = createPublicClient({ chain: baseSepolia, transport: http(RPC_URL) });
const blockNumber = await client.getBlockNumber();
let body = '';
for (const [name, address] of Object.entries(CONTRACTS)) {
  const code = await client.getCode({ address, blockNumber });
  if (!code || code === '0x') throw new Error(`no code at ${address} in block ${blockNumber}`);
  body += `\nexport const ${name}_ADDRESS = '${address}' as const;\nexport const ${name}_CODE = '${code}' as const;\n`;
}
writeFileSync(
  new URL('contracts.ts', import.meta.url),
  `// Generated by fetch.mjs; do not edit. Runtime code copied with eth_getCode from Base Sepolia (chain id 84532) at
// block ${blockNumber}, for the batch-settlement test to install on Anvil with anvil_setCode at the same addresses.
// x402BatchSettlement and ERC3009DepositCollector: https://github.com/x402-foundation/x402 (contracts/evm/src), MIT,
// notice in LICENSE-x402. Multicall3: https://github.com/mds1/multicall3, MIT, notice in LICENSE-multicall3.
${body}`,
);
