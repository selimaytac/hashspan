// Generates the tables of docs/nodes.md from the result files, between its two marker comments: one row per node, one
// row per compared field of each flow with every node's value, and the chain-mode rows. A cell says what the node
// returned or stored; a row that differs from the references is marked with its reason for the gate to look at.
// Usage: node scripts/nodes/table.mjs          (rewrites the tables, `pnpm nodes:table`)
//        node scripts/nodes/table.mjs --check  (fails when the committed tables differ)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { candidates, summarize } from './diff.mjs';
import { RESULTS_DIR } from './result.mjs';

export const DOC = 'docs/nodes.md';
export const START = '<!-- nodes:table:start (generated by `pnpm nodes:table`, do not edit) -->';
export const END = '<!-- nodes:table:end -->';

/** The result files, sorted by node and version. */
export function readResults(root) {
  return readdirSync(join(root, RESULTS_DIR))
    .filter((f) => f.endsWith('.json'))
    .sort()
    .map((file) => ({
      file,
      result: JSON.parse(readFileSync(join(root, RESULTS_DIR, file), 'utf8')),
    }));
}

/** A markdown table cell: backslashes and pipes escaped, line breaks as spaces. */
export const cell = (text) =>
  String(text).replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
const code = (value) => `\`${String(value).replace(/`/g, "'")}\``;
const show = (value) =>
  Array.isArray(value) ? (value.length ? value.join(', ') : 'none') : String(value);

const NODE_COLUMNS = [
  'Node',
  'Version',
  'Chain id',
  'Spec rows matched',
  'Spec differences',
  'Known upstream',
  'Differ from references',
  'Unspecified rows',
  'By design',
  'Unsupported flows',
  'Failed flows',
  'Run',
];

function nodeRow({ file, result }, found) {
  const s = summarize(result);
  const version = result.node.edr
    ? `${result.node.version} (EDR ${result.node.edr})`
    : result.node.version;
  return [
    result.node.title,
    code(version),
    result.genesis?.chainId ?? '-',
    `${s.matched} of ${s.spec}`,
    s.differences,
    s.known + found.filter((c) => c.known).length,
    found.filter((c) => !c.known).length,
    s.recorded,
    s.byDesign,
    s.unsupported,
    s.failed,
    `[${result.runDate}](nodes/results/${file})`,
  ];
}

const key = (r) => `${r.flow}\u0000${r.call}\u0000${r.field}`;

/** Every compared field of the given groups (`flows` or `chainModes`), in the order they first appear. */
function rowsOf(results, group) {
  const rows = new Map();
  for (const { result } of results) {
    for (const f of result[group] ?? []) {
      for (const c of f.checks ?? []) if (!rows.has(key(c))) rows.set(key(c), c);
      if (!(f.checks ?? []).length && !rows.has(`${f.flow}\u0000`)) {
        rows.set(`${f.flow}\u0000`, { flow: f.flow, call: undefined });
      }
    }
  }
  return [...rows.values()].sort(
    (a, b) => order(results, group, a.flow) - order(results, group, b.flow),
  );
}

const order = (results, group, flow) => {
  for (const { result } of results) {
    const i = (result[group] ?? []).findIndex((f) => f.flow === flow);
    if (i !== -1) return i;
  }
  return 0;
};

/** The fields every node that ran a `fields` row has, so a cell shows only what one node has more. */
function commonFields(results, group, row) {
  const lists = results
    .map(({ result }) =>
      (result[group] ?? []).flatMap((f) => f.checks ?? []).find((c) => key(c) === key(row)),
    )
    .filter((c) => Array.isArray(c?.got))
    .map((c) => c.got);
  return lists.length ? lists.reduce((a, b) => a.filter((x) => b.includes(x))) : [];
}

/** One node's cell for one row. */
function valueCell(result, group, row, found, common) {
  const f = (result[group] ?? []).find((x) => x.flow === row.flow);
  if (!f) return '-';
  if (f.status === 'unsupported') return '*unsupported*';
  if (f.status === 'failed' && !(f.checks ?? []).some((c) => key(c) === key(row)))
    return '*failed*';
  const check = (f.checks ?? []).find((c) => key(c) === key(row));
  if (!check) return '-';
  let value =
    row.field === 'fields' && Array.isArray(check.got)
      ? (() => {
          const extra = check.got.filter((x) => !common.includes(x));
          return `${check.got.length} fields${extra.length ? `, also ${extra.join(', ')}` : ''}`;
        })()
      : code(show(check.got));
  if (row.field === 'fields') value = code(value);
  const candidate = found.find((c) => key(c) === key(row));
  const differs = (c) =>
    c.known ? `**${value}** (known: ${c.known})` : `**${value}** (differs: ${c.reason})`;
  if (check.outcome === 'spec-difference' || check.outcome === 'difference') {
    if (check.known) return `**${value}** (known: ${check.known})`;
    return candidate ? differs(candidate) : `**${value}**`;
  }
  if (candidate) return differs(candidate);
  if (check.upstream && check.outcome === 'match')
    return `${value} (${check.upstream}: fixed here)`;
  return value;
}

const expectedCell = (row) => {
  if (row.kind === 'spec') return code(show(row.expected));
  if (row.kind === 'by-design') return `*by design: ${row.mode}*`;
  if (row.expected !== undefined)
    return `${code(show(row.expected))} (${row.upstream ?? 'real chain'})`;
  return '*unspecified*';
};

function detailTable(results, group, first, found) {
  const line = (cells) => `| ${cells.map(cell).join(' | ')} |`;
  const head = [
    first,
    'Call',
    'Field',
    'Expected',
    ...results.map(({ result }) => result.node.title),
  ];
  const lines = [line(head), `|${head.map(() => '---').join('|')}|`];
  for (const row of rowsOf(results, group)) {
    if (row.call === undefined) {
      lines.push(
        line([
          code(row.flow),
          'all',
          '-',
          '-',
          ...results.map(({ result }) => {
            const f = (result[group] ?? []).find((x) => x.flow === row.flow);
            return f ? `*${f.status}*` : '-';
          }),
        ]),
      );
      continue;
    }
    const common = row.field === 'fields' ? commonFields(results, group, row) : [];
    lines.push(
      line([
        code(row.flow),
        row.call,
        row.field,
        expectedCell(row),
        ...results.map(({ result }) => valueCell(result, group, row, found.get(result), common)),
      ]),
    );
  }
  return lines;
}

/** The markdown tables of a list of results. */
export function table(results) {
  if (results.length === 0) return 'No results yet: the first lab run of the matrix writes them.';
  const found = candidates(results.map(({ result }) => result));
  const line = (cells) => `| ${cells.map(cell).join(' | ')} |`;
  const lines = [
    line(NODE_COLUMNS),
    `|${NODE_COLUMNS.map(() => '---').join('|')}|`,
    ...results.map((r) => line(nodeRow(r, found.get(r.result)))),
    '',
    ...detailTable(results, 'flows', 'Flow', found),
  ];
  const withModes = results.filter(({ result }) => (result.chainModes ?? []).length);
  if (withModes.length)
    lines.push('', ...detailTable(withModes, 'chainModes', 'Chain mode', found));
  return lines.join('\n');
}

/** docs/nodes.md with the tables generated from the results. */
export function render(root) {
  const doc = readFileSync(join(root, DOC), 'utf8');
  const start = doc.indexOf(START);
  const end = doc.indexOf(END);
  if (start === -1 || end < start) throw new Error(`${DOC} lacks the table markers`);
  return `${doc.slice(0, start + START.length)}\n\n${table(readResults(root))}\n\n${doc.slice(end)}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = fileURLToPath(new URL('../../', import.meta.url));
  const next = render(root);
  if (process.argv.includes('--check')) {
    if (next !== readFileSync(join(root, DOC), 'utf8')) {
      console.error(`${DOC}: the tables are out of date; run \`pnpm nodes:table\``);
      process.exit(1);
    }
  } else {
    writeFileSync(join(root, DOC), next);
  }
}
