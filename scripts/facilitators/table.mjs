// Generates the tables of docs/facilitators.md from the result files, between its two marker comments: one row per
// target, then one row per compared field of each case with every target's value. A cell says what the facilitator
// returned or what moved on chain.
// Usage: node scripts/facilitators/table.mjs          (rewrites the tables, `pnpm facilitators:table`)
//        node scripts/facilitators/table.mjs --check  (fails when the committed tables differ)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { summarize } from './diff.mjs';
import { RESULTS_DIR } from './result.mjs';

export const DOC = 'docs/facilitators.md';
export const START =
  '<!-- facilitators:table:start (generated by `pnpm facilitators:table`, do not edit) -->';
export const END = '<!-- facilitators:table:end -->';

/** The result files, sorted by target and commit. */
export function readResults(root) {
  return readdirSync(join(root, RESULTS_DIR))
    .filter((f) => f.endsWith('.json'))
    .sort()
    .map((file) => ({
      file,
      result: JSON.parse(readFileSync(join(root, RESULTS_DIR, file), 'utf8')),
    }));
}

const cell = (text) => String(text).replace(/\\/g, '\\\\').replace(/\|/g, '\\|');
const code = (value) => `\`${value}\``;

/**
 * A target's name in the tables: its title, and for a run of another ref than the pinned commit, which one, so a pull
 * request head sits next to the pinned commit as a row of its own.
 */
export function targetLabel(target) {
  if (!target.ref) return target.title;
  return target.pr
    ? `${target.title} (PR #${target.pr} head)`
    : `${target.title} (ref ${target.ref})`;
}

/** Cells of one target's row. */
function targetRow(r, file) {
  const s = summarize(r.conformance);
  const invariants = r.faults.flatMap((f) => f.invariants);
  const holding = invariants.filter((i) => i.holds).length;
  const knownFaults = invariants.filter((i) => !i.holds && i.known).length;
  return [
    targetLabel(r.target),
    code(r.target.commit.slice(0, 8)),
    r.supported.length ? r.supported.join(', ') : 'none',
    `${s.matched} of ${s.spec}`,
    s.differences,
    s.known + knownFaults,
    s.recorded,
    s.unsupported,
    invariants.length ? `${holding} of ${invariants.length} hold` : 'not run',
    r.egress.conformanceRequests,
    `[${r.runDate}](facilitators/results/${file})`,
  ];
}

const TARGET_COLUMNS = [
  'Target',
  'Commit',
  'Schemes offered',
  'Spec rows matched',
  'Spec differences',
  'Known upstream',
  'Unspecified rows',
  'Unsupported cases',
  'Fault invariants',
  'RPC requests seen',
  'Run',
];

/** The compared fields of every case, in the order they first appear, with the case ids no target ran. */
function caseRows(results) {
  const rows = new Map();
  const cases = [];
  for (const { result } of results) {
    for (const c of result.conformance) {
      if (!cases.includes(c.case)) cases.push(c.case);
      for (const check of c.checks ?? []) {
        const key = `${c.case}\u0000${check.step ?? ''}\u0000${check.field}`;
        if (!rows.has(key))
          rows.set(key, { case: c.case, step: check.step, field: check.field, check });
      }
    }
  }
  const out = [];
  for (const id of cases) {
    const fields = [...rows.values()].filter((row) => row.case === id);
    out.push(...(fields.length ? fields : [{ case: id, field: undefined }]));
  }
  return out;
}

/** One target's cell for one field of one case. */
function valueCell(result, row) {
  const c = result.conformance.find((x) => x.case === row.case);
  if (c?.status !== 'run') return '*unsupported*';
  const check = c.checks.find((x) => x.field === row.field && x.step === row.step);
  if (!check) return '-';
  const value = code(check.got);
  if (check.outcome !== 'spec-difference') return value;
  return check.known ? `**${value}** (known: ${check.known})` : `**${value}**`;
}

/** The markdown tables of a list of results. */
export function table(results) {
  if (results.length === 0) return 'No results yet: the first lab run of the matrix writes them.';
  const line = (cells) => `| ${cells.map(cell).join(' | ')} |`;
  const lines = [
    line(TARGET_COLUMNS),
    `|${TARGET_COLUMNS.map(() => '---').join('|')}|`,
    ...results.map(({ file, result }) => line(targetRow(result, file))),
    '',
  ];
  const head = [
    'Case',
    'Field',
    'Spec',
    ...results.map(({ result }) => targetLabel(result.target)),
  ];
  lines.push(line(head), `|${head.map(() => '---').join('|')}|`);
  for (const row of caseRows(results)) {
    if (row.field === undefined) {
      lines.push(line([code(row.case), 'all', '-', ...results.map(() => '*unsupported*')]));
      continue;
    }
    const field = row.step === undefined ? row.field : `${row.field} (step ${row.step})`;
    const expected = row.check.kind === 'spec' ? code(row.check.expected) : '*unspecified*';
    lines.push(
      line([
        code(row.case),
        field,
        expected,
        ...results.map(({ result }) => valueCell(result, row)),
      ]),
    );
  }
  return lines.join('\n');
}

/** docs/facilitators.md with the tables generated from the results. */
export function render(root) {
  const doc = readFileSync(join(root, DOC), 'utf8');
  const start = doc.indexOf(START);
  const end = doc.indexOf(END);
  if (start === -1 || end < start) throw new Error(`${DOC} lacks the table markers`);
  return `${doc.slice(0, start + START.length)}\n\n${table(readResults(root))}\n\n${doc.slice(end)}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = fileURLToPath(new URL('../../', import.meta.url));
  const next = render(root);
  if (process.argv.includes('--check')) {
    if (next !== readFileSync(join(root, DOC), 'utf8')) {
      console.error(`${DOC}: the tables are out of date; run \`pnpm facilitators:table\``);
      process.exit(1);
    }
  } else {
    writeFileSync(join(root, DOC), next);
  }
}
