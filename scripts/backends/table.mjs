// Generates the Compatibility table of docs/backends.md from the result files, between its two marker comments.
// Usage: node scripts/backends/table.mjs          (rewrites the table, `pnpm backends:table`)
//        node scripts/backends/table.mjs --check  (fails when the committed table differs)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CORPUS_ID } from './corpus.mjs';
import { RESULTS_DIR } from './result.mjs';

export const DOC = 'docs/backends.md';
export const START =
  '<!-- backends:table:start (generated by `pnpm backends:table`, do not edit) -->';
export const END = '<!-- backends:table:end -->';

/** The result files, sorted by backend and version. */
export function readResults(root) {
  const dir = join(root, RESULTS_DIR);
  return readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .sort()
    .map((file) => ({ file, result: JSON.parse(readFileSync(join(dir, file), 'utf8')) }));
}

const plural = (n, word) => `${n} ${word}${n === 1 ? '' : 's'}`;

/** Cells of one transport's trace result. */
function traceCells(t) {
  const s = t.summary;
  const x = t.exercised;
  const spans = [
    s.missing && `${s.missing} of ${s.spans} missing`,
    s.nameDiff && `${plural(s.nameDiff, 'name')} differ`,
    s.parentDiff && `${plural(s.parentDiff, 'parent')} differ`,
    s.extraSpans && `${s.extraSpans} extra`,
  ].filter(Boolean);
  const present = s.spans - s.missing;
  let kind = 'kept';
  if (s.kindDiff && s.kindDiff === present) kind = '**dropped**';
  else if (s.kindDiff) kind = `${s.kindDiff} of ${present} differ`;
  let status = s.statusDiff ? `${s.statusDiff} differ` : 'kept';
  if (!s.statusDiff && !x.statusMessage) status = 'code kept (no description sent)';
  const sent = x.attributeTypes.join(', ');
  let types = `kept (${sent})`;
  if (s.attrTypeDiff && s.attrStringified === s.attrTypeDiff) {
    types = `**strings** (${x.attributeTypes.filter((ty) => ty !== 'string').join(', ')} sent)`;
  } else if (s.attrTypeDiff) {
    types = `${s.attrTypeDiff} changed`;
  }
  if (s.attrValueDiff) types += `; ${plural(s.attrValueDiff, 'value')} differ`;
  if (s.attrMissing) types += `; ${s.attrMissing} missing`;
  const names = s.attrNameDiff ? '**dots become underscores**' : 'kept';
  const events =
    s.eventDiff || s.eventAttrDiff ? `${s.eventDiff + s.eventAttrDiff} differ` : 'kept';
  let links = s.linkDiff
    ? `${s.linkDiff} differ`
    : `kept (${x.links}, ${x.crossTraceLinks} across traces)`;
  if (s.linkAttrDiff) links += `; ${s.linkAttrDiff} with attributes changed`;
  const part = (n, read) => (!read || n === null ? 'not read' : n ? `${n} differ` : 'kept');
  const resource = `${part(s.resourceDiff, x.resource)} / ${part(s.scopeDiff, x.scope)}`;
  return {
    spans: spans.length ? spans.join(', ') : 'all kept',
    kind,
    status,
    types,
    names,
    events,
    links,
    resource,
  };
}

/** The metrics cell of one transport. */
function metricCell(m) {
  if (!m) return 'not sent';
  let cell;
  if (m.read)
    cell = m.differences.length
      ? `${plural(m.differences.length, 'metric')} differ`
      : 'counts exact';
  else if (m.status && m.status >= 400) cell = `refused (${m.status})`;
  else cell = 'not read';
  return m.note ? `${cell}: ${m.note}` : cell;
}

const COLUMNS = [
  ['Backend', (r) => `${r.backend.title} ${r.backend.version}`],
  ['Corpus', (r) => `\`${r.corpus.id}\``],
  ['Spans, names, parents', (_r, c) => c.spans],
  ['Kind', (_r, c) => c.kind],
  ['Status', (_r, c) => c.status],
  ['Attribute types', (_r, c) => c.types],
  ['Attribute names', (_r, c) => c.names],
  ['Events', (_r, c) => c.events],
  ['Links', (_r, c) => c.links],
  ['Resource / scope', (_r, c) => c.resource],
  ['Metrics', (_r, c) => c.metrics],
  ['Notes', (r) => r.notes.join('; ')],
  [
    'Run',
    (r, _c, file) =>
      `[${r.runDate}](backends/results/${file}), ${Object.keys(r.transports).join(', ')}`,
  ],
];

/** Cells of a result: a transport's cell, or each transport's value where they differ. */
function cellsOf(result) {
  const per = Object.entries(result.transports).map(([name, t]) => ({
    name,
    cells: { ...traceCells(t.traces), metrics: metricCell(t.metrics) },
  }));
  const out = {};
  for (const key of Object.keys(per[0].cells)) {
    const values = per.map((p) => p.cells[key]);
    out[key] = values.every((v) => v === values[0])
      ? values[0]
      : per.map((p) => `${p.name}: ${p.cells[key]}`).join('; ');
  }
  return out;
}

/** The markdown table of a list of results. */
export function table(results) {
  if (results.length === 0) return 'No results yet: the first lab run of the matrix writes them.';
  const cell = (text) => String(text).replace(/\\/g, '\\\\').replace(/\|/g, '\\|');
  const lines = [
    `| ${COLUMNS.map(([h]) => h).join(' | ')} |`,
    `|${COLUMNS.map(() => '---').join('|')}|`,
  ];
  for (const { file, result } of results) {
    const cells = cellsOf(result);
    lines.push(`| ${COLUMNS.map(([, f]) => cell(f(result, cells, file))).join(' | ')} |`);
  }
  if (!results.some(({ result }) => result.corpus.id === CORPUS_ID)) {
    lines.push(
      '',
      `No backend has a \`${CORPUS_ID}\` result yet: the first lab run of the matrix writes them.`,
    );
  }
  return lines.join('\n');
}

/** docs/backends.md with the table generated from the results. */
export function render(root) {
  const doc = readFileSync(join(root, DOC), 'utf8');
  const start = doc.indexOf(START);
  const end = doc.indexOf(END);
  if (start === -1 || end < start) throw new Error(`${DOC} lacks the table markers`);
  return `${doc.slice(0, start + START.length)}\n\n${table(readResults(root))}\n\n${doc.slice(end)}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = fileURLToPath(new URL('../../', import.meta.url));
  const next = render(root);
  if (process.argv.includes('--check')) {
    if (next !== readFileSync(join(root, DOC), 'utf8')) {
      console.error(`${DOC}: the Compatibility table is out of date; run \`pnpm backends:table\``);
      process.exit(1);
    }
  } else {
    writeFileSync(join(root, DOC), next);
  }
}
